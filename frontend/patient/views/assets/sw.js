const STATIC_CACHE = 'onelife-static-v1';
const STATIC_URLS = [
  '/assets/tailwind.css',
  '/assets/onelife-mark.svg',
  '/assets/onelife-avatar.svg',
  '/assets/onelife-clinician-generated.png',
  '/assets/manifest.webmanifest',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(STATIC_CACHE).then((cache) => cache.addAll(STATIC_URLS)).catch(() => {}),
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((key) => key !== STATIC_CACHE).map((key) => caches.delete(key))),
    ),
  );
  self.clients.claim();
});

// Cache public static CSS/SVG assets only; never cache authenticated patient HTML/API responses.
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith('/assets/')) return;
  event.respondWith(
    caches.match(event.request).then((cached) =>
      cached || fetch(event.request).then((response) => {
        if (response.ok) {
          const clone = response.clone();
          caches.open(STATIC_CACHE).then((cache) => cache.put(event.request, clone)).catch(() => {});
        }
        return response;
      }),
    ),
  );
});
